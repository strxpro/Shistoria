// Resolver: t('hero.title') with optional locale
window.makeT = function(locale) {
  const fallback = window.I18N[locale]?._fallback || null;
  return function t(path) {
    const keys = path.split('.');
    const tryLocale = (loc) => {
      let obj = window.I18N[loc];
      for (const k of keys) {
        if (obj && typeof obj === 'object' && k in obj) obj = obj[k];
        else return undefined;
      }
      return obj;
    };
    let v = tryLocale(locale);
    if (v === undefined && fallback) v = tryLocale(fallback);
    if (v === undefined) v = tryLocale('it');
    return v ?? path;
  };
};

